#!/bin/sh
# gen_games.sh: writes gwl_games.h from gpSP's gba_over.h at the pinned commit,
# the table gpSP's per-game link mode comes from. --check regenerates and
# fails if the committed file differs, so a pin bump cannot leave it stale.
set -e
D=$(cd "$(dirname "$0")/.." && pwd)
# Reuses check_upstream.sh's cached checkout of that commit (last line = path).
SRC=$(sh "$D/tests/check_upstream.sh" | tail -n 1)
HASH=$(basename "$SRC" | sed 's/^gwl_gpsp_//')
OUT=${TMPDIR:-/tmp}
OUT=${OUT%/}/gwl_games.$$.h
trap 'rm -f "$OUT"' EXIT

{
	echo "// gwl_games.h - generated by tests/gen_games.sh from gpSP $HASH gba_over.h."
	echo "// Do not edit. serial is the entry's FLAGS_SERIAL mode, or GWL_GAME_NO_SERIAL."
	echo "// GBA Player entries are GWL_NONE: they still use up gpSP's one serial pick."
	echo "// clang-format off"
	awk '
	function emit(flags,   serial) {
		serial = "GWL_GAME_NO_SERIAL"
		if (flags ~ /FLAGS_SERIAL([^_A-Z]|$)/) {
			if (flags ~ /FLAGS_RFU/) serial = "GWL_RFU"
			else if (flags ~ /FLAGS_SERIAL_POKE/) serial = "GWL_POKE"
			else if (flags ~ /FLAGS_SERIAL_AW1/) serial = "GWL_AW1"
			else if (flags ~ /FLAGS_SERIAL_AW2/) serial = "GWL_AW2"
			else if (flags ~ /FLAGS_GBA_PLAYER/) serial = "GWL_NONE"
			else { print "gen_games: unknown serial flags: " flags > "/dev/stderr"; exit 1 }
		}
		printf "\t{\"%s\", %s, %d, %d},\n", code, serial, \
			(flags ~ /FLAGS_FLASH_128KB/) ? 1 : 0, (flags ~ /FLAGS_EEPROM/) ? 1 : 0
	}
	/^#if 0/ { skip = 1 }
	/^#endif/ { skip = 0; next }
	skip { next }
	/gamepak_code/ && match($0, /"[A-Za-z0-9]+"/) {
		code = substr($0, RSTART + 1, RLENGTH - 2)
		if (length(code) != 4) { print "gen_games: bad code " code > "/dev/stderr"; exit 1 }
		want = 1
		next
	}
	# gba_over.h puts a note between some codes and their flags.
	want && /^[ \t]*\/\*.*\*\/[ \t]*$/ { next }
	want {
		line = $0
		sub(/\/\*.*/, "", line)
		emit(line)
		want = 0
	}' "$SRC/gba_over.h"
} > "$OUT"

if [ "$1" = "--check" ]; then
	diff -u "$D/gwl_games.h" "$OUT" >&2 || { echo "gen_games: gwl_games.h is stale; run tests/gen_games.sh" >&2; exit 1; }
	echo "gen_games: gwl_games.h matches gpSP $HASH" >&2
else
	cp "$OUT" "$D/gwl_games.h"
fi
